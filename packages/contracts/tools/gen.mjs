#!/usr/bin/env node
// `pnpm gen` for packages/contracts. One source, three outputs (D-002):
//   schemas/*.yaml  ──bundle──▶ generated/fiona.schema.json (JSON Schema 2020-12, one $defs namespace)
//                   ──────────▶ generated/ts/types.ts        (json-schema-to-typescript)
//                   ──────────▶ python/fiona_contracts/models.py (datamodel-code-generator, Pydantic v2)
//   services/engine (FastAPI) ─▶ openapi/engine.v1.json ─▶ generated/ts/engine-api.ts (openapi-typescript)
// Everything generated is committed; CI runs `pnpm gen` and fails on any diff.
import { spawnSync } from "node:child_process";
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";
import openapiTS, { astToString } from "openapi-typescript";
import { parse } from "yaml";

const PKG = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const REPO = path.resolve(PKG, "../..");
const rel = (p) => path.relative(REPO, p).split(path.sep).join("/");
const write = (file, text) => {
  mkdirSync(path.dirname(file), { recursive: true });
  writeFileSync(file, text.endsWith("\n") ? text : `${text}\n`);
  console.log(`  wrote ${rel(file)}`);
};
const run = (cmd, args, cwd) => {
  const r = spawnSync(cmd, args, { cwd, stdio: ["ignore", "inherit", "inherit"] });
  if (r.status !== 0) throw new Error(`${cmd} ${args.join(" ")} failed (exit ${r.status})`);
};
const BANNER = "Generated by packages/contracts/tools/gen.mjs from packages/contracts/schemas/*.yaml. Do not edit.";

// ---------------------------------------------------------------- 1. bundle
const defs = {};
const schemaDir = path.join(PKG, "schemas");
for (const file of readdirSync(schemaDir).filter((f) => f.endsWith(".yaml")).sort()) {
  const doc = parse(readFileSync(path.join(schemaDir, file), "utf8"), { merge: true });
  for (const [name, def] of Object.entries(doc.$defs ?? {})) {
    if (defs[name]) throw new Error(`$defs/${name} is defined twice (second time in ${file})`);
    defs[name] = def;
  }
}
const sortedDefs = Object.fromEntries(Object.keys(defs).sort().map((k) => [k, defs[k]]));
const bundle = {
  $schema: "https://json-schema.org/draft/2020-12/schema",
  $id: "https://fiona.local/contracts/v1/fiona.schema.json",
  title: "FionaContracts",
  description: `Fiona contracts v1. ${BANNER}`,
  $defs: sortedDefs,
};

// Every $ref must point at a definition in the bundle.
const missing = new Set();
(function walk(node) {
  if (Array.isArray(node)) return node.forEach(walk);
  if (node && typeof node === "object") {
    if (typeof node.$ref === "string") {
      const m = /^#\/\$defs\/(.+)$/.exec(node.$ref);
      if (!m || !sortedDefs[m[1]]) missing.add(node.$ref);
    }
    Object.values(node).forEach(walk);
  }
})(bundle);
if (missing.size) throw new Error(`Unresolved $ref: ${[...missing].join(", ")}`);

const bundlePath = path.join(PKG, "generated", "fiona.schema.json");
const bundleText = `${JSON.stringify(bundle, null, 2)}\n`;
console.log(`bundle: ${Object.keys(sortedDefs).length} definitions`);
write(bundlePath, bundleText);
write(path.join(PKG, "python", "fiona_contracts", "schema.json"), bundleText);

// ---------------------------------------------------------------- 2. TypeScript types
let ts = await compile(structuredClone(bundle), "FionaContracts", {
  bannerComment: `/* ${BANNER} */`,
  unreachableDefinitions: true,
  additionalProperties: false,
  strictIndexSignatures: true,
  format: true,
});
ts = ts
  .replace(/\n?\/\*\*\n \* This interface was referenced by `FionaContracts`'s JSON-Schema\n \* via the `definition` "[^"]+"\.\n \*\/\n/g, "\n")
  .replace(/^export interface FionaContracts \{[\s\S]*?^\}\n/m, "")
  .replace(/\n{3,}/g, "\n\n");
write(path.join(PKG, "generated", "ts", "types.ts"), ts);

// ---------------------------------------------------------------- 3. Pydantic models
const modelsPath = path.join(PKG, "python", "fiona_contracts", "models.py");
run(
  "uv",
  [
    "run", "--project", "tools", "datamodel-codegen",
    "--input", rel(bundlePath).replace("packages/contracts/", ""),
    "--input-file-type", "jsonschema",
    "--output", "python/fiona_contracts/models.py",
    "--output-model-type", "pydantic_v2.BaseModel",
    "--target-python-version", "3.12",
    "--use-standard-collections", "--use-union-operator", "--use-annotated", "--field-constraints",
    "--enum-field-as-literal", "all", "--collapse-root-models", "--use-double-quotes",
    "--disable-timestamp", "--formatters", "builtin",
    "--custom-file-header", `# ${BANNER}`,
  ],
  PKG,
);
let py = readFileSync(modelsPath, "utf8").replace(/\r\n/g, "\n");
const classes = [...py.matchAll(/^class (\w+)\(/gm)].map((m) => m[1]).filter((c) => c !== "FionaContracts");
py = `${py.trimEnd()}\n\n\n__all__ = [\n${classes.sort().map((c) => `    "${c}",`).join("\n")}\n]\n`;
write(modelsPath, py);

// ---------------------------------------------------------------- 4. Engine OpenAPI -> typed client
const openapiPath = path.join(PKG, "openapi", "engine.v1.json");
run("uv", ["run", "--project", "engine", "python", "../packages/contracts/tools/dump_openapi.py", rel(openapiPath)], path.join(REPO, "services"));
const ast = await openapiTS(new URL(`file:///${openapiPath.split(path.sep).join("/")}`), { alphabetize: true });
write(path.join(PKG, "generated", "ts", "engine-api.ts"), `/* Generated by packages/contracts/tools/gen.mjs from the engine's OpenAPI. Do not edit. */\n\n${astToString(ast)}`);

console.log("contracts: generated OK");
